#!/usr/bin/env node
// Builds supabase/seed.sql from content/*.json.
// Usage: node scripts/build-seed.mjs
// The Supabase CLI runs seed.sql on `supabase db reset`; you can also paste it
// into the SQL editor of your Supabase project.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => JSON.parse(readFileSync(join(root, "content", f), "utf8"));
const content = read("content.json");
const stories = existsSync(join(root, "content", "stories.json")) ? read("stories.json") : {};
const rawMnemonics = existsSync(join(root, "content", "mnemonics.json")) ? read("mnemonics.json") : {};
// Keys may be a word id or the exact German entry (then it applies in every chapter).
const mnemonics = {};
for (const w of content.words) {
  const m = rawMnemonics[w.id] ?? rawMnemonics[w.de];
  if (m) mnemonics[w.id] = m;
}
const unused = Object.keys(rawMnemonics).filter((k) => !k.startsWith("_") && !content.words.some((w) => w.id === k || w.de === k));
if (unused.length) console.warn("mnemonics with no matching word:", unused.join(", "));

const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (typeof v === "object") return q(JSON.stringify(v)) + "::jsonb";
  return "'" + String(v).replace(/'/g, "''") + "'";
};
const rows = (list) => list.map((r) => "(" + r.map(q).join(", ") + ")").join(",\n");

const out = [];
out.push("-- Generated by scripts/build-seed.mjs. Do not edit by hand.");
out.push("begin;");

out.push(`insert into public.chapters (id, kind, title, subtitle, bn_title, sort, story) values
${rows(content.chapters.map((c) => [c.id, c.kind, c.title, c.subtitle, c.bn_title, c.sort, stories[c.id] ?? null]))}
on conflict (id) do update set kind = excluded.kind, title = excluded.title, subtitle = excluded.subtitle,
  bn_title = excluded.bn_title, sort = excluded.sort, story = excluded.story;`);

out.push(`insert into public.lessons (id, chapter_id, num, title, en_title, bn_title, kind, sort, notes_html, exercises) values
${rows(content.lessons.map((l) => [l.id, l.chapter_id, l.num, l.title, l.en_title, l.bn_title, l.kind, l.sort, l.notes_html, l.exercises]))}
on conflict (id) do update set chapter_id = excluded.chapter_id, num = excluded.num, title = excluded.title,
  en_title = excluded.en_title, bn_title = excluded.bn_title, kind = excluded.kind, sort = excluded.sort,
  notes_html = excluded.notes_html, exercises = excluded.exercises;`);

out.push(`delete from public.sentences where lesson_id in (${content.lessons.map((l) => q(l.id)).join(", ")});`);
for (let i = 0; i < content.sentences.length; i += 200) {
  const chunk = content.sentences.slice(i, i + 200);
  out.push(`insert into public.sentences (lesson_id, idx, de, en, bn, say, emoji, tip, grp, is_list) values
${rows(chunk.map((s) => [s.lesson_id, s.idx, s.de, s.en, s.bn, s.say, s.emoji, s.tip, s.grp, s.is_list]))};`);
}

for (let i = 0; i < content.words.length; i += 200) {
  const chunk = content.words.slice(i, i + 200);
  out.push(`insert into public.words (id, chapter_id, kind, de, en, bn, say, topic, emoji, tip, mnemonic, sort) values
${rows(chunk.map((w, j) => [w.id, w.chapter_id, w.kind, w.de, w.en, w.bn, w.say, w.topic, w.emoji, w.tip, mnemonics[w.id] ?? "", i + j]))}
on conflict (id) do update set chapter_id = excluded.chapter_id, kind = excluded.kind, de = excluded.de, en = excluded.en,
  bn = excluded.bn, say = excluded.say, topic = excluded.topic, emoji = excluded.emoji, tip = excluded.tip,
  mnemonic = case when excluded.mnemonic <> '' then excluded.mnemonic else public.words.mnemonic end, sort = excluded.sort;`);
}

const links = content.words.flatMap((w) => w.lessons.map((l) => [w.id, l]));
out.push(`delete from public.word_lessons where word_id in (select id from public.words where chapter_id in (${content.chapters.map((c) => q(c.id)).join(", ")}));`);
for (let i = 0; i < links.length; i += 400) {
  out.push(`insert into public.word_lessons (word_id, lesson_id) values
${rows(links.slice(i, i + 400))}
on conflict do nothing;`);
}

out.push("commit;");
writeFileSync(join(root, "supabase", "seed.sql"), out.join("\n\n") + "\n");
console.log(`seed.sql: ${Object.keys(mnemonics).length} mnemonics, ${Object.keys(stories).length} stories, ${content.chapters.length} chapters, ${content.lessons.length} lessons, ${content.sentences.length} sentences, ${content.words.length} words, ${links.length} links`);
